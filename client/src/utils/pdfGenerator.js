/**
 * PDF Report Generator using jsPDF
 *
 * Exports an accessibility audit report containing metadata, score,
 * violation summary, and itemized WCAG issues.
 */

import { jsPDF } from "jspdf";
import { getViolationIssue, getViolationFix } from "./remediation";

export function generatePdfReport(scan) {
  if (!scan) return;

  const doc = new jsPDF({
    orientation: "portrait",
    unit: "pt",
    format: "a4"
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 40;
  const contentWidth = pageWidth - margin * 2;
  let y = margin;

  function checkPageBreak(requiredHeight = 30) {
    if (y + requiredHeight > pageHeight - margin) {
      doc.addPage();
      y = margin;
    }
  }

  // Header Title
  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.setTextColor(23, 32, 51); // Dark navy
  doc.text("Website Accessibility Audit Report", margin, y);
  y += 24;

  // Subtitle / Tool branding
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(100, 116, 139);
  doc.text("Generated by Accessibility Inspector (Automated axe-core Audit)", margin, y);
  y += 18;

  // Divider
  doc.setDrawColor(226, 232, 240);
  doc.setLineWidth(1);
  doc.line(margin, y, pageWidth - margin, y);
  y += 20;

  // Scan Metadata Section
  doc.setFont("helvetica", "bold");
  doc.setFontSize(12);
  doc.setTextColor(30, 41, 59);
  doc.text("Scan Overview", margin, y);
  y += 16;

  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(51, 65, 85);

  const formattedDate = scan.timestamp ? new Date(scan.timestamp).toLocaleString() : "N/A";
  doc.text(`URL: ${scan.url || "N/A"}`, margin, y);
  y += 14;
  doc.text(`Page Title: ${scan.pageTitle || "N/A"}`, margin, y);
  y += 14;
  doc.text(`Audit Date: ${formattedDate}`, margin, y);
  y += 14;
  if (scan.scanDurationMs) {
    doc.text(`Scan Duration: ${(scan.scanDurationMs / 1000).toFixed(2)}s`, margin, y);
    y += 14;
  }
  y += 10;

  // Score Box
  checkPageBreak(50);
  doc.setFillColor(248, 250, 252);
  doc.setDrawColor(203, 213, 225);
  doc.roundedRect(margin, y, contentWidth, 42, 4, 4, "FD");

  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  const score = scan.score ?? "N/A";
  doc.setTextColor(score >= 80 ? 22 : score >= 50 ? 180 : 220, score >= 80 ? 101 : score >= 50 ? 83 : 38, score >= 80 ? 52 : 9);
  doc.text(`Accessibility Score: ${score} / 100`, margin + 14, y + 26);
  y += 56;

  // Summary Metrics Breakdown
  checkPageBreak(70);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(12);
  doc.setTextColor(30, 41, 59);
  doc.text("Summary Metrics", margin, y);
  y += 16;

  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(51, 65, 85);

  const totalViolations = scan.totalViolations ?? scan.violations?.length ?? 0;
  const totalPassed = scan.totalPassed ?? 0;
  const totalIncomplete = scan.totalIncomplete ?? 0;
  const totalElements = scan.totalAffectedElements ?? 0;

  doc.text(`Total Rule Violations: ${totalViolations}`, margin, y);
  doc.text(`Passed Checks: ${totalPassed}`, margin + 180, y);
  y += 14;
  doc.text(`Affected Elements: ${totalElements}`, margin, y);
  doc.text(`Incomplete / Review Checks: ${totalIncomplete}`, margin + 180, y);
  y += 18;

  // Severity Breakdown
  const sev = scan.severityCounts || { critical: 0, serious: 0, moderate: 0, minor: 0 };
  doc.setFont("helvetica", "bold");
  doc.text("Severity Breakdown:", margin, y);
  y += 14;
  doc.setFont("helvetica", "normal");
  doc.text(
    `Critical: ${sev.critical || 0}  |  Serious: ${sev.serious || 0}  |  Moderate: ${sev.moderate || 0}  |  Minor: ${sev.minor || 0}`,
    margin,
    y
  );
  y += 24;

  // Violations Detail List
  checkPageBreak(40);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(12);
  doc.setTextColor(30, 41, 59);
  doc.text(`Detected Violations (${totalViolations})`, margin, y);
  y += 16;

  if (!scan.violations || scan.violations.length === 0) {
    doc.setFont("helvetica", "italic");
    doc.setFontSize(10);
    doc.setTextColor(100, 116, 139);
    doc.text("Zero automated accessibility violations detected.", margin, y);
    y += 20;
  } else {
    scan.violations.forEach((v, index) => {
      checkPageBreak(70);

      // Violation Card Header
      doc.setFont("helvetica", "bold");
      doc.setFontSize(10);
      doc.setTextColor(23, 32, 51);
      doc.text(`${index + 1}. [${(v.impact || "minor").toUpperCase()}] ${v.id}`, margin, y);
      y += 14;

      doc.setFont("helvetica", "normal");
      doc.setFontSize(9);
      doc.setTextColor(71, 85, 105);

      // Issue (wrapped)
      doc.setFont("helvetica", "bold");
      doc.text("Issue: ", margin + 10, y);
      doc.setFont("helvetica", "normal");
      const issueLines = doc.splitTextToSize(getViolationIssue(v), contentWidth - 55);
      doc.text(issueLines, margin + 45, y);
      y += issueLines.length * 11 + 4;

      // Fix (wrapped)
      doc.setFont("helvetica", "bold");
      doc.text("Fix: ", margin + 10, y);
      doc.setFont("helvetica", "normal");
      const fixLines = doc.splitTextToSize(getViolationFix(v), contentWidth - 55);
      doc.text(fixLines, margin + 45, y);
      y += fixLines.length * 11 + 4;

      // Tags & Node count
      const tagsStr = Array.isArray(v.tags) ? v.tags.slice(0, 4).join(", ") : "";
      doc.text(`WCAG / Category: ${tagsStr || "N/A"}  |  Affected Elements: ${v.nodeCount || v.nodes?.length || 0}`, margin + 10, y);
      y += 14;

      if (v.helpUrl) {
        doc.setTextColor(37, 99, 235);
        doc.text(`Documentation: ${v.helpUrl}`, margin + 10, y);
        y += 14;
        doc.setTextColor(71, 85, 105);
      }

      y += 6;
    });
  }

  // Save the PDF
  let safeHost = "website";
  if (scan.url) {
    try {
      safeHost = new URL(scan.url).hostname.replace(/[^a-z0-9]/gi, "_");
    } catch {
      safeHost = "website";
    }
  }

  const dateStr = new Date().toISOString().split("T")[0];
  doc.save(`accessibility_report_${safeHost}_${dateStr}.pdf`);
}
